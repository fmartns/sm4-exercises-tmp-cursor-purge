class Sm4Test(TestCase):
    def test_rotl(self):
        self.assertEqual(rotl(0x80000000, 1), 0x00000001)
        self.assertEqual(rotl(0x12345678, 8), 0x34567812)
        self.assertEqual(rotl(0xABCDEF01, 0), 0xABCDEF01)
        self.assertEqual(rotl(0xABCDEF01, 32), 0xABCDEF01)

    def test_load_store(self):
        block = bytes.fromhex("0123456789abcdeffedcba9876543210")
        self.assertEqual(load_u32_be(block, 0), 0x01234567)
        self.assertEqual(load_u32_be(block, 1), 0x89ABCDEF)
        self.assertEqual(load_u32_be(block, 2), 0xFEDCBA98)
        self.assertEqual(load_u32_be(block, 3), 0x76543210)
        self.assertEqual(store_u32_be(0x01234567), bytes.fromhex("01234567"))
        self.assertEqual(store_u32_be(0xFEDCBA98), bytes.fromhex("fedcba98"))

    def test_SM4_T_non_lin_sub(self):
        # SM4_S[0x01]=0x90, [0x23]=0xF4, [0x45]=0x73, [0x67]=0xA2
        self.assertEqual(SM4_T_non_lin_sub(0x01234567), 0x90F473A2)
        self.assertEqual(
            SM4_T_non_lin_sub(0x00000000),
            (SM4_S[0] << 24) | (SM4_S[0] << 16) | (SM4_S[0] << 8) | SM4_S[0],
        )

    def test_SM4_T_slow(self):
        t = SM4_T_non_lin_sub(0x01234567)
        expected = t
        for n in (2, 10, 18, 24):
            expected ^= (((t << n) & MASK_32) | (t >> (32 - n))) & MASK_32
        self.assertEqual(SM4_T_slow(0x01234567), expected & MASK_32)

    def test_SM4_key_sub(self):
        t = SM4_T_non_lin_sub(0x01234567)
        expected = t
        for n in (13, 23):
            expected ^= (((t << n) & MASK_32) | (t >> (32 - n))) & MASK_32
        self.assertEqual(SM4_key_sub(0x01234567), expected & MASK_32)

    def test_ossl_sm4_set_key(self):
        rk = ossl_sm4_set_key(OFFICIAL_KEY)
        self.assertEqual(len(rk), 32)
        self.assertEqual(rk[0], 0xF12186F9)
        self.assertEqual(rk[1], 0x41662B61)
        self.assertEqual(rk[31], 0x9124A012)

    def test_ossl_sm4_encrypt(self):
        self.assertEqual(ossl_sm4_encrypt(OFFICIAL_PLAINTEXT, OFFICIAL_KEY), OFFICIAL_CIPHERTEXT)

    def test_ossl_sm4_decrypt(self):
        ciphertext = ossl_sm4_encrypt(OFFICIAL_PLAINTEXT, OFFICIAL_KEY)
        self.assertEqual(ossl_sm4_decrypt(ciphertext, OFFICIAL_KEY), OFFICIAL_PLAINTEXT)
        self.assertEqual(ossl_sm4_decrypt(OFFICIAL_CIPHERTEXT, OFFICIAL_KEY), OFFICIAL_PLAINTEXT)
